<#
.SYNOPSIS
  Фильтр вывода router-сервера: убирает строки-«пустышки».

.DESCRIPTION
  Роутер пересылает вывод дочерней модели (llama-server) построчно, но при
  загрузке весов та рисует прогресс одиночными символами \r. Роутер считает
  каждый \r отдельной строкой и печатает "[pid] " без текста — это и есть
  лавина пустых строк. Скрипт читает stdin построчно и пропускает только такие
  пустые строки; всё содержательное (загрузка модели, статистика генерации,
  ошибки) проходит как есть. Вывод идёт в stdout немедленно.

  stderr родительского процесса сюда не попадает (в .bat он не перенаправлен),
  поэтому логи роутера видны в консоли напрямую.
#>
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$in = [Console]::In
while ($null -ne ($line = $in.ReadLine())) {
    # пустая строка "[pid] " (прогресс загрузки) или просто пустая — в мусор
    if ($line -match '^\[\d+\]\s*$' -or $line -match '^\s*$') { continue }
    [Console]::Out.WriteLine($line)
}
